#pragma once

namespace tl
{

namespace detail
{
	
/*!
 * \brief Determines if a value is negative.
 * \tparam T The type of the value.
 * \param t The value to check.
 * \return -1 if the value is negative, 1 otherwise.
 */
template<typename T>
constexpr auto isNegative(T t) -> int
{
    return t < 0 ? -1 : 1;
}

} // namespace detail

} // namespace tl
